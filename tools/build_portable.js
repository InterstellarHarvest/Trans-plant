#!/usr/bin/env node
'use strict';
/* Builds engine/js/portable_data.js — the file:// (double-click) data
 * bundle. Browsers refuse fetch()/XHR from file:// pages (Chromium and
 * Safari; Firefox happens to allow it), so index.html loads this
 * generated classic script instead when opened from disk. Served over
 * http (Pages, python3 -m http.server) the engine still fetches the
 * real JSON and this file is never loaded.
 *
 * Contents (all keyed by the same relative path the engine requests):
 *   modules — every modules/**\/*.json, parsed
 *   sheets  — every sprites/npc/**\/spritesheet.json, trimmed to the
 *             frame filenames (the only field scene_art.js reads), and
 *             every station approach sheet (frame rects + meta.size)
 *   images  — data: URIs for the few images file:// would break: ones the
 *             engine reads pixels back from (a disk image taints the
 *             canvas) and CSS mask-image sources (CORS fetch). The title
 *             menu's universal overlay and its rotation backgrounds are
 *             here for the first reason: the menu composites them once in
 *             a canvas and exports the result (background-views.js)
 *
 * Usage (from the Trans-plant root):
 *   node tools/build_portable.js           write the bundle
 *   node tools/build_portable.js --check   exit 1 if it is stale
 * lint_modules.js runs the --check, so a stale bundle fails lint.
 * REBUILD AFTER ANY modules/, NPC OR STATION-APPROACH spritesheet.json CHANGE,
 * AND AFTER ANY CHANGE TO THE MENU OVERLAY OR A ROTATION BACKGROUND.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = 'engine/js/portable_data.js';
const IMAGES = [
  'sprites/minigames/hullbreach/breach_patch.png',             // weld bake reads pixels
  'sprites/minigames/engine/bg_engine_error_relay.png',        // engine-repair hover masks
  'sprites/minigames/engine/bg_engine_error_ignition.png',     //   (CSS mask-image is a CORS
  'sprites/minigames/engine/bg_engine_error_coolant.png',      //   fetch, refused on file://)
  'sprites/minigames/engine/bg_engine_error_fuel.png',
  // Pause-menu sidebar icons — also CSS masks (shared.js PauseMenu), so
  // they rendered blank on a double-click launch.
  ...['resume', 'settings', 'save', 'load', 'log', 'help', 'quit'].map(n => 'sprites/interface/pause/' + n + '.png'),
  // Title menu (MENU-002C1): the one room overlay and every background in
  // the rotation (an approved background joins this list when it joins the
  // rotation). Keyed as background-views.js requests them.
  'resources/sprites/interface/menu/menu_overlay.png',
  'resources/sprites/interface/menu/backgrounds/earth.png',
  'resources/sprites/interface/menu/backgrounds/mars.png',   // Mars V3 (MENU-002D)
  'resources/sprites/interface/menu/backgrounds/ringed.png', // Ringed V2-B (MENU-002H)
  'resources/sprites/interface/menu/backgrounds/nebula.png', // Nebula V1 (MENU-002H)
];

function walk(rel, test, out = []) {
  for (const e of fs.readdirSync(path.join(ROOT, rel), { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : 1)) {
    const r = rel + '/' + e.name;
    // sprites/ is a symlink to resources/sprites — follow it via statSync.
    if (fs.statSync(path.join(ROOT, r)).isDirectory()) walk(r, test, out);
    else if (test(e.name)) out.push(r);
  }
  return out;
}

function build() {
  const readJSON = rel => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
  const modules = {};
  for (const rel of walk('modules', n => n.endsWith('.json'))) modules[rel] = readJSON(rel);
  const sheets = {};
  for (const rel of walk('sprites/npc', n => n === 'spritesheet.json')) {
    const j = readJSON(rel);
    sheets[rel] = { frames: (Array.isArray(j.frames) ? j.frames : []).map(f => ({ filename: f.filename || '' })) };
  }
  // Station approach sheets (scene_art.js approach mode): frame rects
  // and the sheet size are what the frame cycler reads.
  for (const rel of walk('sprites/backgrounds/station/approach', n => n === 'spritesheet.json')) {
    const j = readJSON(rel);
    const frames = Array.isArray(j.frames) ? j.frames : Object.values(j.frames || {});
    sheets[rel] = { frames: frames.map(f => ({ filename: f.filename || '', frame: f.frame })), meta: { size: (j.meta || {}).size } };
  }
  const images = {};
  for (const rel of IMAGES) images[rel] = 'data:image/png;base64,' + fs.readFileSync(path.join(ROOT, rel)).toString('base64');
  const data = { modules, sheets, images };
  return '/* GENERATED by tools/build_portable.js — do not edit by hand.\n'
    + ' * file:// data bundle: modules ' + Object.keys(modules).length
    + ', sheets ' + Object.keys(sheets).length + ', images ' + Object.keys(images).length + '. */\n'
    + 'window.TP_PORTABLE = ' + JSON.stringify(data) + ';\n';
}

if (require.main === module) {
  const next = build();
  const outPath = path.join(ROOT, OUT);
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
    if (cur !== next) { console.error(`build_portable: ${OUT} is STALE — run: node tools/build_portable.js`); process.exit(1); }
    console.log(`build_portable: ${OUT} is up to date.`);
  } else {
    fs.writeFileSync(outPath, next);
    console.log(`build_portable: wrote ${OUT} (${next.length.toLocaleString()} bytes).`);
  }
}

module.exports = { build, OUT };
